// Writes src/client/palettes.css (the default seeds and the colour roles derived from them) and
// tests/fixtures/seeds.json (what the server must write for each built-in preset, which the PHP
// tests compare against). `npm run palettes`; the tests fail while either is stale.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { BUILTINS, FALLBACK } from '../src/client/lib/builtins.ts';
import { DERIVED, SCHEMES, STATUS, seeds, type Scheme, type SchemeColors, type Seeds } from '../src/client/lib/palette.ts';
import { onColor } from '../src/client/lib/color.ts';

const pct = (share: number) => `${Math.round(share * 1000) / 10}%`;
const block = (selector: string, lines: string[]) => `${selector} {\n${lines.map((l) => (l ? `    ${l}` : '')).join('\n')}\n}\n`;

/** The custom properties one scheme's seeds become; the server writes the same names. */
export function seedLines(s: Seeds): string[] {
    const lines = [
        `--ts-bg: ${s.bg};`,
        `--ts-surface: ${s.surface};`,
        `--ts-text: ${s.text};`,
        `--ts-primary: ${s.primary};`,
        `--ts-primary-fg: ${s.primaryFg};`,
        `--ts-link: ${s.link};`,
        `--ts-link-fg: ${s.linkFg};`,
    ];
    if (s.success) lines.push(`--ts-success: ${s.success};`, `--ts-success-fg: ${s.successFg};`);
    if (s.warning) lines.push(`--ts-warning: ${s.warning};`, `--ts-warning-fg: ${s.warningFg};`);
    if (s.destructive) lines.push(`--ts-destructive: ${s.destructive};`, `--ts-destructive-fg: ${s.destructiveFg};`, `--ts-danger: ${s.danger};`);
    return lines;
}

function roles(scheme: Scheme): string[] {
    const d = DERIVED[scheme];
    const status = STATUS[scheme];
    const dark = scheme === 'dark';

    return [
        `--color-scheme: ${scheme};`,
        `--background: var(--ts-bg);`,
        `--foreground: var(--ts-text);`,
        `--card: var(--ts-surface);`,
        `--card-foreground: var(--ts-text);`,
        `--popover: color-mix(in oklab, var(${dark ? '--ts-surface' : '--ts-bg'}) ${pct(d.popover)}, var(--ts-text));`,
        `--popover-foreground: var(--ts-text);`,
        `--secondary: var(--popover);`,
        `--secondary-foreground: var(--ts-text);`,
        `--muted: color-mix(in oklab, var(--ts-surface) ${pct(d.muted)}, var(--ts-bg));`,
        `--muted-foreground: color-mix(in oklab, var(--ts-text) ${pct(d.mutedForeground)}, var(--ts-surface));`,
        dark ? `--sunken: var(--ts-bg);` : `--sunken: color-mix(in oklab, var(--ts-surface) 92%, var(--ts-text));`,
        `--border: color-mix(in oklab, var(--ts-surface) ${pct(d.border)}, var(--ts-text));`,
        dark ? `--input: color-mix(in oklab, var(--ts-bg) 60%, var(--ts-surface));` : `--input: var(--ts-surface);`,
        `--input-border: var(--border);`,
        `--primary: var(--ts-primary);`,
        `--primary-foreground: var(--ts-primary-fg);`,
        `--accent: var(--ts-link);`,
        `--accent-foreground: var(--ts-link-fg);`,
        `--ring: var(--ts-link);`,
        `--selection: color-mix(in oklab, var(--ts-primary) ${pct(d.selection)}, var(--ts-bg));`,
        `--selection-foreground: var(--ts-text);`,
        `--theme-color: var(--ts-bg);`,
        '',
        `--success: var(--ts-success, ${status.success});`,
        `--success-foreground: var(--ts-success-fg, ${onColor(status.success)});`,
        `--warning: var(--ts-warning, ${status.warning});`,
        `--warning-foreground: var(--ts-warning-fg, ${onColor(status.warning)});`,
        `--destructive: var(--ts-destructive, ${status.danger});`,
        `--destructive-foreground: var(--ts-destructive-fg, ${onColor(status.danger)});`,
        `--caution: ${status.caution};`,
        `--caution-foreground: ${onColor(status.caution)};`,
        `--state-foreground: ${onColor(status.success)};`,
        `--ts-danger-text: var(--ts-danger, ${status.dangerText});`,
        '',
        dark
            ? `--terminal-background: color-mix(in oklab, var(--ts-bg) 70%, black);`
            : `--terminal-background: color-mix(in oklab, var(--ts-text) 94%, var(--ts-bg));`,
        `--terminal-foreground: #d4d4d4;`,
        `--editor-background: var(--terminal-background);`,
    ];
}

export function renderCss(): string {
    let css = '/* Generated by palettes/build.ts from resources/presets.json: run `npm run palettes`. */\n\n';
    css += `/*\n * ${BUILTINS[FALLBACK].name}, until the server's stylesheet for the active preset (imported at the top\n * of theme.css) sets the seeds with :root:root. The roles below derive everything else from them.\n */\n`;
    for (const scheme of SCHEMES) css += block(`:root.${scheme}`, seedLines(seeds(BUILTINS[FALLBACK][scheme], scheme)));
    for (const scheme of SCHEMES) {
        css += `\n/* The colour roles of the ${scheme} scheme; the editor's preview derives the same way. */\n`;
        css += block(`:root.${scheme},\n.ts-preview[data-scheme='${scheme}']`, roles(scheme));
    }
    return css;
}

/**
 * Each built-in preset and a few samples: the colours and the seeds they become, per scheme.
 * src/Support/Palette.php must write the same seeds; the PHP tests check it.
 */
export function renderFixture(): string {
    const out: Record<string, { colors: Record<Scheme, SchemeColors>; seeds: Record<Scheme, Seeds> }> = {};
    const add = (id: string, colors: Record<Scheme, SchemeColors>) => {
        out[id] = { colors, seeds: Object.fromEntries(SCHEMES.map((scheme) => [scheme, seeds(colors[scheme], scheme)])) as Record<Scheme, Seeds> };
    };
    for (const [id, preset] of Object.entries(BUILTINS)) add(id, { dark: preset.dark, light: preset.light });
    // Presets as an admin might build them: no secondary, status colours, colours that read badly.
    const samples: Record<string, SchemeColors> = {
        'sample-no-secondary': { background: '#101010', surface: '#1a1a1a', text: '#f0f0f0', primary: '#9b3735' },
        'sample-status': { background: '#fdf6e3', surface: '#ffffff', text: '#222222', primary: '#f59e0b', success: '#22c55e', warning: '#eab308', danger: '#ef4444' },
        'sample-poor': { background: '#777777', surface: '#808080', text: '#999999', primary: '#888888', secondary: '#7a7a7a', danger: '#ff0000' },
    };
    for (const [id, colors] of Object.entries(samples)) add(id, { dark: colors, light: colors });
    return JSON.stringify(out, null, 4) + '\n';
}

export const CSS_OUTPUT = fileURLToPath(new URL('../src/client/palettes.css', import.meta.url));
export const FIXTURE_OUTPUT = fileURLToPath(new URL('../tests/fixtures/seeds.json', import.meta.url));

if (import.meta.url === `file://${process.argv[1]}`) {
    writeFileSync(CSS_OUTPUT, renderCss());
    writeFileSync(FIXTURE_OUTPUT, renderFixture());
    console.log('wrote src/client/palettes.css and tests/fixtures/seeds.json');
}
