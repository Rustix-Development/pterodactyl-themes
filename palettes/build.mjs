// Writes src/palettes.css from presets.mjs: `npm run palettes`. The tests fail when the file is stale.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { onColor } from './color.mjs';
import { DERIVED, PRESETS, SEASONS, STATUS } from './presets.mjs';

const pct = (share) => `${Math.round(share * 1000) / 10}%`;
const block = (selector, lines) => `${selector} {\n${lines.map((l) => (l ? `    ${l}` : '')).join('\n')}\n}\n`;

function seeds(s) {
    const lines = [
        `--ts-bg: ${s.bg};`,
        `--ts-surface: ${s.surface};`,
        `--ts-text: ${s.text};`,
        `--ts-primary: ${s.primary};`,
        `--ts-primary-fg: ${onColor(s.primary)};`,
        `--ts-link: ${s.link};`,
        `--ts-link-fg: ${onColor(s.link)};`,
    ];
    if (s.effect) lines.push(`--ts-effect: ${s.effect};`);
    return lines;
}

/** The custom colour settings a season sets aside while it is on. */
const CUSTOM = ['accent', 'dark-background', 'dark-surface', 'dark-text', 'light-background', 'light-surface', 'light-text'];

function roles(scheme) {
    const d = DERIVED[scheme];
    const status = STATUS[scheme];
    const dark = scheme === 'dark';
    const custom = (name) => `--ts-custom-${scheme}-${name}`;

    return [
        `--color-scheme: ${scheme};`,
        // A custom colour wins over the preset's seed; a custom background alone brings a matching surface.
        `--ts-auto-surface: color-mix(in oklab, var(${custom('background')}) ${dark ? '93%, white' : '35%, white'});`,
        `--ts-b: var(${custom('background')}, var(--ts-bg));`,
        `--ts-s: var(${custom('surface')}, var(--ts-auto-surface, var(--ts-surface)));`,
        `--ts-t: var(${custom('text')}, var(--ts-text));`,
        // The custom accent, with text that reads on it and a version of it that reads as text.
        `--ts-custom-primary-fg: oklch(from var(--ts-custom-accent) clamp(0.18, (0.62 - l) * 1000, 0.99) 0 0);`,
        dark
            ? `--ts-custom-link: oklch(from var(--ts-custom-accent) max(l, 0.8) min(c, 0.13) h);`
            : `--ts-custom-link: oklch(from var(--ts-custom-accent) min(l, 0.47) c h);`,
        `--ts-custom-link-fg: oklch(from var(--ts-custom-accent) ${dark ? '0.18' : '0.99'} 0 0);`,
        '',
        `--background: var(--ts-b);`,
        `--foreground: var(--ts-t);`,
        `--card: var(--ts-s);`,
        `--card-foreground: var(--ts-t);`,
        `--popover: color-mix(in oklab, var(${dark ? '--ts-s' : '--ts-b'}) ${pct(d.popover)}, var(--ts-t));`,
        `--popover-foreground: var(--ts-t);`,
        `--secondary: var(--popover);`,
        `--secondary-foreground: var(--ts-t);`,
        `--muted: color-mix(in oklab, var(--ts-s) ${pct(d.muted)}, var(--ts-b));`,
        `--muted-foreground: color-mix(in oklab, var(--ts-t) ${pct(d.mutedForeground)}, var(--ts-s));`,
        dark ? `--sunken: var(--ts-b);` : `--sunken: color-mix(in oklab, var(--ts-s) 92%, var(--ts-t));`,
        `--border: color-mix(in oklab, var(--ts-s) ${pct(d.border)}, var(--ts-t));`,
        dark ? `--input: color-mix(in oklab, var(--ts-b) 60%, var(--ts-s));` : `--input: var(--ts-s);`,
        `--input-border: var(--border);`,
        `--primary: var(--ts-custom-accent, var(--ts-primary));`,
        `--primary-foreground: var(--ts-custom-primary-fg, var(--ts-primary-fg));`,
        `--accent: var(--ts-custom-link, var(--ts-link));`,
        `--accent-foreground: var(--ts-custom-link-fg, var(--ts-link-fg));`,
        `--ring: var(--accent);`,
        `--selection: color-mix(in oklab, var(--primary) ${pct(d.selection)}, var(--ts-b));`,
        `--selection-foreground: var(--ts-t);`,
        `--theme-color: var(--ts-b);`,
        '',
        `--success: ${status.success};`,
        `--success-foreground: ${onColor(status.success)};`,
        `--warning: ${status.warning};`,
        `--warning-foreground: ${onColor(status.warning)};`,
        `--destructive: ${status.destructive};`,
        `--destructive-foreground: ${onColor(status.destructive)};`,
        `--caution: ${status.caution};`,
        `--caution-foreground: ${onColor(status.caution)};`,
        `--state-foreground: ${onColor(status.success)};`,
        `--ts-danger: ${status.danger};`,
        '',
        dark
            ? `--terminal-background: color-mix(in oklab, var(--ts-b) 70%, black);`
            : `--terminal-background: color-mix(in oklab, var(--ts-t) 94%, var(--ts-b));`,
        `--terminal-foreground: #d4d4d4;`,
        `--editor-background: var(--terminal-background);`,
    ];
}

export function render() {
    let css = '/* Generated by palettes/build.mjs from palettes/presets.mjs: edit those and run `npm run palettes`. */\n\n';
    const [first] = Object.keys(PRESETS);

    css += `/* ${PRESETS[first].name} is the preset until one is chosen. */\n`;
    for (const scheme of ['dark', 'light']) css += block(`:root.${scheme}`, seeds(PRESETS[first][scheme]));

    for (const [id, preset] of Object.entries(PRESETS)) {
        if (id === first) continue;
        css += `\n/* ${preset.name} */\n`;
        for (const scheme of ['dark', 'light']) css += block(`:root.${scheme}[data-ts-preset='${id}']`, seeds(preset[scheme]));
    }

    for (const [id, season] of Object.entries(SEASONS)) {
        const on = `:is([data-ts-season='${id}'], [data-ts-season-on='${id}'])`;
        css += `\n/* ${season.name}: chosen, or on by the calendar in auto mode. It sets the custom colours aside. */\n`;
        for (const scheme of ['dark', 'light']) {
            css += block(`:root.${scheme}${on}`, [
                ...seeds(season[scheme]),
                ...CUSTOM.map((name) => `--ts-custom-${name}: initial;`),
            ]);
        }
    }

    for (const scheme of ['dark', 'light']) {
        css += `\n/* The colour roles of the ${scheme} scheme, from the seeds above. */\n`;
        css += block(`:root.${scheme}`, roles(scheme));
    }

    return css;
}

export const OUTPUT = fileURLToPath(new URL('../src/palettes.css', import.meta.url));

if (import.meta.url === `file://${process.argv[1]}`) {
    writeFileSync(OUTPUT, render());
    console.log('wrote src/palettes.css');
}
